/// Whether `code` is an officially assigned ISO 3166-1 alpha-2 code (upper case).
pub fn is_country_code(code: &str) -> bool {
    ISO_3166_ALPHA2.binary_search(&code).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_complete_sorted_and_unique() {
        assert_eq!(ISO_3166_ALPHA2.len(), 249, "officially assigned codes");
        assert!(
            ISO_3166_ALPHA2.windows(2).all(|w| w[0] < w[1]),
            "sorted for binary search, no duplicates"
        );
    }

    #[test]
    fn lookups() {
        for ok in ["GB", "US", "NG", "IN", "AE", "KE"] {
            assert!(is_country_code(ok), "{ok}");
        }
        for bad in ["gb", "UK", "EU", "XX", "", "GBR"] {
            assert!(!is_country_code(bad), "{bad}");
        }
    }
}
