#!/usr/bin/env python3
"""Generates crates/pos-receipts/src/codepage_tables.rs from Python's `codecs` module.

Run from anywhere:

    python3 crates/pos-receipts/tools/gen_codepages.py

and review the diff. rustfmt skips the generated module (`#[rustfmt::skip]` in codepage.rs).

Every table maps the bytes 0x80..=0xFF of one single-byte code page to Unicode. The bytes
0x00..=0x7F are ASCII on every page the encoder uses, so they are not tabulated (CP864's
0x25 ARABIC PERCENT SIGN is deliberately ignored: the encoder never sends 0x25 as anything
but `%`). A byte that the codec cannot decode, or that decodes to a control character (the
C1 range of the ISO pages), is `'\\0'`: unassigned, never used for encoding.

The tables are never edited by hand.
"""

import codecs
import os
import unicodedata

# (Rust constant, Python codec, bytes to take from it). The JIS X0201 page is the
# half-width katakana half of Shift-JIS: only 0xA1..=0xDF are single bytes there.
PAGES = [
    ("CP437", "cp437", range(0x80, 0x100)),
    ("CP737", "cp737", range(0x80, 0x100)),
    ("CP775", "cp775", range(0x80, 0x100)),
    ("CP850", "cp850", range(0x80, 0x100)),
    ("CP852", "cp852", range(0x80, 0x100)),
    ("CP855", "cp855", range(0x80, 0x100)),
    ("CP857", "cp857", range(0x80, 0x100)),
    ("CP858", "cp858", range(0x80, 0x100)),
    ("CP860", "cp860", range(0x80, 0x100)),
    ("CP861", "cp861", range(0x80, 0x100)),
    ("CP862", "cp862", range(0x80, 0x100)),
    ("CP863", "cp863", range(0x80, 0x100)),
    ("CP864", "cp864", range(0x80, 0x100)),
    ("CP865", "cp865", range(0x80, 0x100)),
    ("CP866", "cp866", range(0x80, 0x100)),
    ("CP869", "cp869", range(0x80, 0x100)),
    ("CP1250", "cp1250", range(0x80, 0x100)),
    ("CP1251", "cp1251", range(0x80, 0x100)),
    ("CP1252", "cp1252", range(0x80, 0x100)),
    ("CP1253", "cp1253", range(0x80, 0x100)),
    ("CP1254", "cp1254", range(0x80, 0x100)),
    ("CP1255", "cp1255", range(0x80, 0x100)),
    ("CP1256", "cp1256", range(0x80, 0x100)),
    ("CP1257", "cp1257", range(0x80, 0x100)),
    ("CP1258", "cp1258", range(0x80, 0x100)),
    ("ISO_8859_1", "iso8859_1", range(0x80, 0x100)),
    ("ISO_8859_2", "iso8859_2", range(0x80, 0x100)),
    ("ISO_8859_7", "iso8859_7", range(0x80, 0x100)),
    ("ISO_8859_15", "iso8859_15", range(0x80, 0x100)),
    ("JIS_X0201", "shift_jis", range(0xA1, 0xE0)),
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "codepage_tables.rs")


def table(codec, take):
    chars = []
    for b in range(0x80, 0x100):
        ch = "\0"
        if b in take:
            try:
                ch = bytes([b]).decode(codec)
            except UnicodeDecodeError:
                ch = "\0"
            if len(ch) != 1 or unicodedata.category(ch) == "Cc":
                ch = "\0"
        chars.append(ch)
    return chars


def rust_char(ch):
    return "'\\0'" if ch == "\0" else "'\\u{%X}'" % ord(ch)


def main():
    lines = [
        "// @generated by crates/pos-receipts/tools/gen_codepages.py from Python's `codecs`",
        "// module. Do not edit by hand: change the script and run",
        "//     python3 crates/pos-receipts/tools/gen_codepages.py",
        "// Each table is the Unicode character for the bytes 0x80..=0xFF; '\\0' is unassigned.",
        "",
    ]
    for const, codec, take in PAGES:
        chars = table(codec, take)
        assigned = sum(1 for c in chars if c != "\0")
        lines.append(f"/// `{codec}`: {assigned} characters in 0x80..=0xFF.")
        lines.append(f"pub(crate) static {const}: [char; 128] = [")
        for row in range(0, 128, 8):
            cells = ", ".join(rust_char(c) for c in chars[row : row + 8])
            lines.append(f"    {cells}, // 0x{0x80 + row:02X}")
        lines.append("];")
        lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
